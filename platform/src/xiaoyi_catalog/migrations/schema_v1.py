def create_missing(connection, names):
    existing = set(inspect(connection).get_table_names())
    dialect = connection.dialect.name
    if dialect not in {"sqlite", "postgresql"}:
        raise RuntimeError("Unsupported catalogue database")
    for name, variants in SCHEMA.items():
        if name in names and name not in existing:
            ddl = variants[dialect]
            connection.exec_driver_sql(ddl["table"])
            for index in ddl["indexes"]:
                connection.exec_driver_sql(index)
